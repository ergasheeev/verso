/**
 * The Verso atlas — the country layer the whole app is organised around.
 *
 * This is the frontend’s copy of what will live in the `Country` table. It is
 * kept as a typed module (rather than fetched) for three reasons: the country
 * hub’s chrome — flag, currency, emergency numbers, calling code — must paint
 * on first frame with no request, this same array is what seeds the database,
 * and the `Continent`/`PriceLevel` unions below are what the filter UI is
 * typed against.
 *
 * Emergency numbers are the one field here that can get someone hurt if it is
 * wrong, so each is the country’s own published number rather than an assumed
 * regional default. Where a country runs the pan-European 112 alongside its
 * own three-digit services, both are listed — 112 works from a foreign SIM
 * with no credit, the local numbers usually reach a dispatcher faster.
 */

export type Continent =
  | "Europe"
  | "Asia"
  | "Africa"
  | "Oceania"
  | "North America"
  | "South America";

/** 1 = shoestring, 4 = expensive. Drives the $–$$$$ mark in the atlas grid. */
export type PriceLevel = 1 | 2 | 3 | 4;

export interface Emergency {
  /** Universal or police number a traveller should try first. */
  primary: string;
  police?: string;
  ambulance?: string;
  fire?: string;
  /** Some countries run a dedicated tourist-police line; it is worth surfacing. */
  tourist?: string;
}

export interface Country {
  /** ISO 3166-1 alpha-2. Primary key in the database. */
  code: string;
  slug: string;
  name: string;
  continent: Continent;
  capital: string;
  /** ISO 4217. */
  currency: string;
  currencyName: string;
  languages: string[];
  callingCode: string;
  flag: string;
  /** Centroid, for the atlas map and distance sorting. */
  lat: number;
  lng: number;
  priceLevel: PriceLevel;
  bestSeason: string;
  visaNote: string;
  tagline: string;
  summary: string;
  emergency: Emergency;
  /** Surfaces on the atlas landing rail. */
  featured?: boolean;

  /* ── Facts contributed by verso-dataset ──────────────────────────────
     Optional across the board: the dataset covers 45 of the 51 countries
     here, and every surface that reads these already renders without them. */
  /** e.g. "9.9 million". A display string, not a number — the precision
   *  varies by source and rounding it here would invent accuracy. */
  population?: string;
  /** e.g. "83 600 km²". */
  area?: string;
  /** e.g. "UTC+4 (GST)". */
  timezone?: string;
  /** Socket letters and mains voltage, e.g. "G (220V)". */
  plugType?: string;
  drivingSide?: "left" | "right";
  /** 1–5, editorial rather than an index anyone publishes. */
  safetyRating?: number;
  /** Count of UNESCO World Heritage sites. */
  unesco?: number;
  topCities?: string[];
  cuisine?: string[];
}

